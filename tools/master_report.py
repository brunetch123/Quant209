"""Summarise the archive-wide comparison and look for what to improve.

Consumes the CSVs written by ``tools/master_bench.py`` and asks, of the whole archive
rather than one run: where does automated integration disagree with the analyst, and does
the disagreement track something actionable: a congener, a signal level, a flag, a boundary
rule, an instrument era?

    python tools/master_report.py --data docs/validation/master \
        --out docs/validation/MASTER-REPORT.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

import quant209  # noqa: F401  (BLAS guards before numpy does any work)

#: Rows below these are near the detection limit, where the analyst's own manual
#: integration is imprecise and the lab censors the result. Headline agreement is
#: therefore quoted on the detectable subset, with the remainder reported separately.
MIN_AREA = 1000.0
MIN_MASS = 1.0
#: The agreement band every comparison in this project is scored against.
BAND = 0.25


def add_rpd(df: pd.DataFrame) -> pd.DataFrame:
    """Symmetric relative percent difference, 0 where both sides are 0."""
    mean = (df["auto"] + df["manual"]) / 2.0
    df["rpd"] = np.where(mean != 0, (df["auto"] - df["manual"]) / mean.replace(0, np.nan), 0.0)
    return df


def summarise(df: pd.DataFrame, label: str) -> dict:
    if df.empty:
        return {"what": label, "n": 0, "med": np.nan, "band": np.nan,
                "bias": np.nan, "ratio": np.nan}
    a = df["rpd"].abs()
    manual_sum = df["manual"].sum()
    return {
        "what": label,
        "n": len(df),
        "med": a.median(),
        "band": (a <= BAND).mean(),
        "bias": df["rpd"].median(),
        "ratio": df["auto"].sum() / manual_sum if manual_sum else np.nan,
    }


def fmt(key: str, value) -> str:
    if isinstance(value, (int, np.integer)):
        return f"{value:,}"
    if isinstance(value, float):
        if np.isnan(value):
            return "--"
        if key == "band":
            return f"{value * 100:.1f}%"
        if key == "med":
            return f"{value * 100:.1f}%"
        if key == "bias":
            return f"{value * 100:+.1f}%"
        return f"{value:.3f}"
    return str(value)


def table(rows: list[dict], cols: list[tuple[str, str]]) -> str:
    out = ["| " + " | ".join(c[1] for c in cols) + " |",
           "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(fmt(k, r.get(k, "")) for k, _ in cols) + " |")
    return "\n".join(out)


HEAD = [("what", "group"), ("n", "n"), ("med", "median |RPD|"),
        ("band", "within +/-25%"), ("bias", "median RPD (bias)"), ("ratio", "total ratio")]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=Path("docs/validation/master"))
    ap.add_argument("--out", type=Path, default=Path("docs/validation/MASTER-REPORT.md"))
    ap.add_argument("--title", default="Archive-wide comparison against analyst quantification")
    args = ap.parse_args(argv)

    areas = add_rpd(pd.read_csv(args.data / "areas.csv"))
    masses = add_rpd(pd.read_csv(args.data / "masses.csv"))
    recs = pd.read_csv(args.data / "recoveries.csv")
    runs = pd.read_csv(args.data / "runs.csv")
    for df in (areas, masses):
        df["flags"] = df["flags"].fillna("-")

    nat_a = areas[areas["role"] == "native"].copy()
    det_a = nat_a[nat_a["manual"] >= MIN_AREA]
    nat_m = masses[masses["role"] == "native"].copy()
    det_m = nat_m[nat_m["manual"] >= MIN_MASS]

    L: list[str] = []
    add = L.append
    add(f"# {args.title}\n")
    add(f"Generated by `tools/master_report.py` from `{args.data.as_posix()}`.")
    add("`RPD = (auto - manual) / mean`, so it is symmetric and bounded at +/-200%.")
    add(f"Headline figures cover **native** analytes whose *manual* value clears the "
        f"detectability floor (area >= {MIN_AREA:,.0f} counts*s, mass >= {MIN_MASS:.0f} ng). "
        f"Rows below the floor are reported separately rather than folded in: the analyst's "
        f"own integration is imprecise there and the lab censors those results anyway, so "
        f"including them would let noise dominate a number meant to measure the method.\n")

    # 1. headline -------------------------------------------------------------
    add("## 1. Headline\n")
    n_ok = int((runs["status"] == "ok").sum())
    add(f"- **{n_ok} runs** compared, of {len(runs)} folders in the archive "
        f"({int((runs['status'] == 'no-truth').sum())} hold no analyst quantification, "
        f"{int((runs['status'] == 'error').sum())} could not be processed).")
    add(f"- **{len(areas):,}** area comparisons pooled, of which **{len(det_a):,}** are "
        f"detectable native rows; **{len(det_m):,}** detectable native mass rows.")
    add(f"- **{len(recs):,}** surrogate-recovery comparisons.\n")
    add(table([summarise(det_a, "Areas, detectable"),
               summarise(nat_a[nat_a["manual"] < MIN_AREA], "Areas, below floor"),
               summarise(det_m, "Masses, detectable"),
               summarise(nat_m[nat_m["manual"] < MIN_MASS], "Masses, below floor")],
              [("what", "level")] + HEAD[1:]))
    if not recs.empty:
        err = (recs["auto"] - recs["manual"]).abs()
        add(f"\nSurrogate recoveries: **MAE {err.mean():.4f}** (median {err.median():.4f}), "
            f"n={len(recs):,}.")

    # 2. per run --------------------------------------------------------------
    add("\n## 2. By run\n")
    add("Worst first, by detectable-area median |RPD|. A run far from the pack is usually "
        "one systematic problem rather than many independent errors. A retention-time table "
        "that does not fit, a different instrument method, or a mis-keyed workbook "
        "so this table is the first place to look for a fixable cause.\n")
    per_run = []
    for run, g in det_a.groupby("run"):
        s = summarise(g, run)
        gm = det_m[det_m["run"] == run]
        s["mass_med"] = gm["rpd"].abs().median() if not gm.empty else np.nan
        rr = runs[runs["run"] == run]
        s["fit"] = str(rr["fit_ok"].iloc[0]) if not rr.empty else ""
        per_run.append(s)
    per_run.sort(key=lambda r: -(0 if np.isnan(r["med"]) else r["med"]))
    add(table(per_run, [("what", "run"), ("n", "n"), ("med", "area median |RPD|"),
                        ("band", "within band"), ("mass_med", "mass median |RPD|"),
                        ("ratio", "area ratio"), ("fit", "RT fit ok")]))

    # 3. signal level ---------------------------------------------------------
    add("\n## 3. Does agreement depend on signal level?\n")
    edges = [0, 1e2, 1e3, 1e4, 1e5, 1e6, np.inf]
    names = ["<100", "100 - 1k", "1k - 10k", "10k - 100k", "100k - 1M", "> 1M"]
    nat_a["level"] = pd.cut(nat_a["manual"], bins=edges, labels=names, right=False)
    add(table([summarise(g, str(b)) for b, g in nat_a.groupby("level", observed=True)],
              [("what", "manual area (counts*s)")] + HEAD[1:]))

    # 4. flags and boundary rule ---------------------------------------------
    add("\n## 4. By integration flag\n")
    rows = [summarise(nat_a[nat_a["flags"].str.contains(f, na=False)], f)
            for f in ("absent", "low_sn", "narrow", "clustered", "shoulder", "forced", "displaced",
                      "apportioned", "realigned")]
    rows.append(summarise(nat_a[nat_a["flags"] == "-"], "(unflagged)"))
    add(table(rows, [("what", "flag")] + HEAD[1:]))
    add("\n### By boundary rule\n")
    add(table([summarise(g, str(m)) for m, g in nat_a.groupby("method")],
              [("what", "method")] + HEAD[1:]))

    # 5. detection disagreement ----------------------------------------------
    add("\n## 5. Detection disagreement\n")
    add("The expensive disagreements are not small differences in a shared peak but "
        "whether there is a peak at all.\n")
    has_manual = nat_a["manual"] >= MIN_AREA
    we_absent = nat_a["flags"].str.contains("absent", na=False)
    missed = nat_a[has_manual & we_absent]
    invented = nat_a[(~has_manual) & (~we_absent) & (nat_a["auto"] >= MIN_AREA)]
    denom_rows = max(int(has_manual.sum()), 1)
    denom_area = max(float(nat_a.loc[has_manual, "manual"].sum()), 1.0)
    add(f"- **Analyst integrated it, we call it absent: {len(missed):,} rows** "
        f"({len(missed) / denom_rows * 100:.1f}% of detectable rows), carrying "
        f"{missed['manual'].sum() / denom_area * 100:.1f}% of the analyst's total "
        f"detectable area.")
    add(f"- **We integrated it, the analyst did not: {len(invented):,} rows.**\n")
    if not missed.empty:
        top = (missed.groupby("label")
               .agg(n=("label", "size"), med=("manual", "median"))
               .sort_values("n", ascending=False).head(20))
        add("Congeners most often called absent while the analyst integrated them:\n")
        add(table([{"what": lab, "n": int(r.n), "ratio": float(r.med)}
                   for lab, r in top.iterrows()],
                  [("what", "congener"), ("n", "rows"), ("ratio", "median manual area")]))

    # 6. per congener ---------------------------------------------------------
    add("\n## 6. Congeners that disagree repeatedly\n")
    add("Congeners with at least 50 detectable rows, worst median |RPD| first. A congener "
        "with a consistent *signed* bias points at a rule rather than at noise, such as a "
        "boundary, a co-elution assignment or a retention-time anchor.\n")
    g = det_a.groupby("label")
    per_lab = pd.DataFrame({
        "n": g.size(),
        "med": g["rpd"].apply(lambda s: s.abs().median()),
        "bias": g["rpd"].median(),
        "band": g["rpd"].apply(lambda s: (s.abs() <= BAND).mean()),
        "homolog": g["homolog"].first(),
    })
    per_lab = per_lab[per_lab["n"] >= 50].sort_values("med", ascending=False)
    add(table([{"what": lab, "ratio": r.homolog, "n": int(r.n), "med": r.med,
                "bias": r.bias, "band": r.band} for lab, r in per_lab.head(30).iterrows()],
              [("what", "congener"), ("ratio", "homolog"), ("n", "n"),
               ("med", "median |RPD|"), ("bias", "median RPD (bias)"), ("band", "within band")]))

    # 7. homolog --------------------------------------------------------------
    add("\n## 7. By homolog\n")
    order = ["mono", "di", "tri", "tetra", "penta", "hexa", "hepta", "octa", "nona", "deca"]
    add(table([summarise(det_a[det_a["homolog"] == h], h) for h in order],
              [("what", "homolog")] + HEAD[1:]))

    # 8. runs contributing nothing -------------------------------------------
    bad = runs[runs["status"] != "ok"]
    if not bad.empty:
        add("\n## 8. Runs contributing no comparison\n")
        add(table([{"what": r.run, "n": r.status, "ratio": str(r.note)[:90]}
                   for r in bad.itertuples()],
                  [("what", "run"), ("n", "status"), ("ratio", "why")]))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
